# Write src/pages/work/help/shotGeometry.js from the capture run's geo.json.
import json, sys
from pathlib import Path
# Usage: python scripts/help-shots/geo2js.py <workdir> <repo>
S = Path(sys.argv[1]).resolve()
REPO = Path(sys.argv[2])
geo = json.loads((S / 'geo.json').read_text())
out = REPO / 'src/pages/work/help/shotGeometry.js'
old = {}
if out.exists():
    import re
    # keep entries of shots this run did not capture (a partial run never drops geometry)
    txt = out.read_text(encoding='utf8')
    m = re.search(r'export const SHOT_GEOMETRY = (\{.*\})\s*$', txt, re.S)
    if m: old = json.loads(m.group(1))
merged = {**old, **geo}
lines = [
    '// GENERATED by the help-screenshot capture run (scripts/help-shots/README.md):',
    '// the size of each annotated help screenshot under public/help/<name>.webp and',
    '// each callout region [x, y, width, height] in image pixels, measured from the',
    '// real DOM element in the same run that took the picture, so a highlight can',
    '// never drift from its screenshot. Re-run the capture to refresh; do not edit.',
    'export const SHOT_GEOMETRY = ' + json.dumps({k: merged[k] for k in sorted(merged)}, indent=2),
    '',
]
out.write_text('\n'.join(lines), encoding='utf8', newline='\n')
print(len(merged), 'shots')
