// Regenerate public/sitemap.xml - a multilingual sitemap for admireveda.com.
//
// WHAT: one <url> per PUBLIC route, each carrying an <xhtml:link rel="alternate">
// for every supported locale (hreflang = the locale's BCP-47 tag, href = the
// clean path with ?lang=<code>) plus an x-default pointing at the clean path.
// Language on WorkCoPilot is client-side and ?lang is the top-priority signal
// (see src/i18n/index.jsx detectLocale), so each alternate URL renders that
// language for a crawler that runs our JS. This mirrors the per-page hreflang
// that useSeo.js emits at runtime, so the sitemap and the live <head> agree.
//
// SINGLE SOURCE: the locale list is imported from src/i18n/locales.js (never
// re-typed here), and the route list below is the one place the public routes +
// their crawl hints live for the sitemap.
//
// WHY A SCRIPT: the set of locales or routes changes over time; regenerating is
// one command and the output is committed. Pure Node, no dependency, no network.
//
// Usage:
//   node scripts/gen-sitemap.mjs            write public/sitemap.xml
//   node scripts/gen-sitemap.mjs --check    exit 1 if the file is out of date
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { LOCALES } from '../src/i18n/locales.js'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const OUT = path.join(ROOT, 'public', 'sitemap.xml')
const ORIGIN = 'https://admireveda.com'
const argv = process.argv.slice(2)

// Public, indexable routes. `loc` is the clean canonical path; changefreq +
// priority are crawl hints. Marketing first, then legal/compliance.
const ROUTES = [
  { loc: '/',                            changefreq: 'weekly',  priority: '1.0' },
  { loc: '/workcopilot',                 changefreq: 'monthly', priority: '0.9' },
  { loc: '/workcopilot/how-it-works',    changefreq: 'monthly', priority: '0.8' },
  { loc: '/workcopilot/use-cases',       changefreq: 'monthly', priority: '0.8' },
  { loc: '/workcopilot/fields',          changefreq: 'monthly', priority: '0.8' },
  { loc: '/workcopilot/security',        changefreq: 'monthly', priority: '0.8' },
  { loc: '/workcopilot/enterprise',      changefreq: 'monthly', priority: '0.7' },
  { loc: '/workcopilot/company-brain',   changefreq: 'monthly', priority: '0.7' },
  // no /workcopilot/pricing: admireveda.com publishes no prices (it redirects to contact)
  { loc: '/workcopilot/benchmark',       changefreq: 'monthly', priority: '0.6' },
  { loc: '/workcopilot/faq',             changefreq: 'monthly', priority: '0.7' },
  { loc: '/workcopilot/contact',         changefreq: 'monthly', priority: '0.6' },
  { loc: '/demo',                        changefreq: 'monthly', priority: '0.6' },
  { loc: '/affiliate',                   changefreq: 'monthly', priority: '0.6' },
  // Legal + compliance (English content; the page chrome still localizes).
  { loc: '/workcopilot/privacy',         changefreq: 'yearly',  priority: '0.3' },
  { loc: '/workcopilot/terms',           changefreq: 'yearly',  priority: '0.3' },
  { loc: '/workcopilot/acceptable-use',  changefreq: 'yearly',  priority: '0.3' },
  { loc: '/workcopilot/cookie-policy',   changefreq: 'yearly',  priority: '0.3' },
  { loc: '/workcopilot/dpa',             changefreq: 'yearly',  priority: '0.3' },
  { loc: '/workcopilot/subprocessors',   changefreq: 'yearly',  priority: '0.3' },
  { loc: '/workcopilot/refund',          changefreq: 'yearly',  priority: '0.3' },
  { loc: '/workcopilot/disclaimer',      changefreq: 'yearly',  priority: '0.3' },
  { loc: '/workcopilot/accessibility',   changefreq: 'yearly',  priority: '0.3' },
]

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')

function alternates(loc) {
  const lines = LOCALES.map(
    (l) => `    <xhtml:link rel="alternate" hreflang="${esc(l.tag)}" href="${esc(ORIGIN + loc)}?lang=${encodeURIComponent(l.code)}"/>`,
  )
  lines.push(`    <xhtml:link rel="alternate" hreflang="x-default" href="${esc(ORIGIN + loc)}"/>`)
  return lines.join('\n')
}

function build() {
  const urls = ROUTES.map((r) => (
    `  <url>\n` +
    `    <loc>${esc(ORIGIN + r.loc)}</loc>\n` +
    `${alternates(r.loc)}\n` +
    `    <changefreq>${r.changefreq}</changefreq>\n` +
    `    <priority>${r.priority}</priority>\n` +
    `  </url>`
  )).join('\n')
  return `<?xml version="1.0" encoding="UTF-8"?>\n` +
    `<!-- Generated by scripts/gen-sitemap.mjs. Do not edit by hand; re-run the script. -->\n` +
    `<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">\n` +
    `${urls}\n` +
    `</urlset>\n`
}

const xml = build()

if (argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : ''
  if (cur.replace(/\r\n/g, '\n') !== xml) {
    console.error('sitemap: public/sitemap.xml is out of date; run `node scripts/gen-sitemap.mjs`')
    process.exit(1)
  }
  console.log('sitemap: up to date')
} else {
  fs.writeFileSync(OUT, xml)
  console.log(`sitemap: wrote ${ROUTES.length} url(s) x ${LOCALES.length} locales + x-default -> public/sitemap.xml`)
}
